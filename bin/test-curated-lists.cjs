const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const data = require('../server/data/curated-lists.json');
const compiled = ts.transpileModule(fs.readFileSync(path.join(root, 'server/lib/curatedLists.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const mod = {exports:{}};
vm.runInNewContext(compiled, { exports: mod.exports, require: name => name.includes('/data/') ? {default:data} : require(name), Intl, Date });
const { dailyCategories, validateLists } = mod.exports;
const ids = result => Array.from(result.results, list => list.id);
const beforeMidnight = dailyCategories(undefined, new Date('2026-10-11T05:59:59Z'));
const morning = dailyCategories(undefined, new Date('2026-10-10T06:00:00Z'));
const tomorrow = dailyCategories(undefined, new Date('2026-10-11T06:00:00Z'));
assert.equal(beforeMidnight.day, '2026-10-10');
assert.equal(tomorrow.day, '2026-10-11');
assert.deepEqual(ids(beforeMidnight), ids(morning));
assert.notDeepEqual(ids(beforeMidnight), ids(tomorrow));
assert.deepEqual(ids(morning), ids(dailyCategories([...data.lists].reverse(), new Date('2026-10-10T06:00:00Z'))));
assert.equal(morning.results.length,15);
assert.equal(new Set(ids(morning)).size,15);
const expanded = dailyCategories(undefined, new Date('2026-10-10T12:00:00Z'),25);
assert.equal(expanded.results.length,25);
assert.equal(new Set(ids(expanded)).size,25);
assert.deepEqual(ids(expanded).slice(0,15),ids(morning));
assert.equal(dailyCategories(data.lists.slice(0,4), new Date(),25).results.length,4);
const expandedTomorrow = dailyCategories(undefined,new Date('2026-10-11T06:00:00Z'),25);
const originalItems = JSON.stringify(data.lists);
const artFixture = [data.lists.find(list => list.items.length > 5)];
const artToday = dailyCategories(artFixture,new Date('2026-10-10T06:00:00Z')).results[0];
const artLater = dailyCategories(artFixture,new Date('2026-10-11T05:59:59Z')).results[0];
const artTomorrow = dailyCategories(artFixture,new Date('2026-10-11T06:00:00Z')).results[0];
assert.equal(JSON.stringify(artToday.covers), JSON.stringify(artLater.covers));
assert.notEqual(JSON.stringify(artToday.covers), JSON.stringify(artTomorrow.covers));
assert.equal(artToday.covers.length,5);
assert.equal(artToday.cover, artToday.covers[0]);
for(const item of artToday.covers) assert.ok(artFixture[0].items.includes(item));
assert.equal(JSON.stringify(data.lists), originalItems);
for(const category of morning.results) assert.equal(JSON.stringify(category.covers), JSON.stringify(expanded.results.find(x=>x.id===category.id).covers));
assert.deepEqual(ids(expandedTomorrow).slice(0,15),ids(tomorrow));
assert.equal(dailyCategories(data.lists.slice(0,4)).results.length,4);
assert.equal(dailyCategories([]).results.length,0);
assert.equal(validateLists(data).length,115);
assert.throws(()=>validateLists({version:2,lists:[]}));
assert.throws(()=>validateLists({version:1,lists:[data.lists[0],data.lists[0]]}));
assert.throws(()=>validateLists({version:1,lists:[{...data.lists[0],items:[{type:'movie',tmdbId:-1}]}]}));
for(const list of data.lists) assert.ok(list.title.en && list.title.es && list.description.en && list.description.es);
const yaml = require('js-yaml').load(fs.readFileSync(path.join(root, 'seerr-api.yml'), 'utf8'));
for(const route of ['/curated','/curated/random','/curated/{id}']) assert.ok(yaml.paths[route].get);
console.log(`PASS: ${data.lists.length} categories validated; daily stability, Merida midnight rollover, deterministic order, max 15, small/empty sets, invalid inputs and API declarations`);
