const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const path = require('node:path');
const root = path.resolve(__dirname,'..');
const exportsObject = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(path.join(root,'server/constants/discover.ts'),'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{exports:exportsObject});
const {DiscoverSliderType:T,defaultSliders,reconcileDiscoverySliders:reconcile}=exportsObject;
const plain = x => JSON.parse(JSON.stringify(x));
assert.equal(T.TMDB_TV_STREAMING_SERVICES,21); // Existing persisted IDs must never shift.
assert.deepEqual([T.WATCHING_NOW,T.RECENTLY_WATCHED,T.RECOMMENDATIONS],[22,23,24]);
const fresh = plain(defaultSliders);
const idx = type => fresh.findIndex(s=>s.type===type);
assert.equal(idx(T.WATCHING_NOW),idx(T.RECENT_REQUESTS)+1);
assert.equal(idx(T.RECENTLY_WATCHED),idx(T.WATCHING_NOW)+1);
assert.equal(idx(T.RECOMMENDATIONS),idx(T.STUDIOS)+1);
const existing=fresh.filter(s=>s.type<22).reverse().map((s,i)=>({...s,id:100+i,order:i,enabled:s.type!==T.RECENT_REQUESTS}));
existing.splice(2,0,{id:999,type:T.TMDB_SEARCH,title:'Custom',data:'test',enabled:false,isBuiltIn:false});
const upgraded=plain(reconcile(existing));
assert.deepEqual(upgraded.filter(s=>s.id).map(({order,...s})=>s),existing.map(({order,...s})=>s));
assert.equal(upgraded.find(s=>s.type===T.WATCHING_NOW).enabled,false);
assert.equal(upgraded.find(s=>s.type===T.RECENTLY_WATCHED).enabled,false);
const customized=upgraded.reverse().map((s,order)=>({...s,order,enabled:s.type!==T.RECOMMENDATIONS}));
assert.deepEqual(plain(reconcile(customized)),customized);
assert.equal(new Set(upgraded.map(s=>s.type)).size,upgraded.length);
const partial=customized.filter(s=>s.type!==T.RECENTLY_WATCHED);
assert.equal(reconcile(partial).filter(s=>s.type===T.RECENTLY_WATCHED).length,1);
const view=fs.readFileSync(path.join(root,'src/components/Discover/index.tsx'),'utf8');
for(const name of ['WATCHING_NOW','RECENTLY_WATCHED','RECOMMENDATIONS']) assert.ok(view.includes(`case DiscoverSliderType.${name}:`));
assert.ok(!view.includes('<RecentRequestsSlider /><WatchingNowSlider />'));
assert.ok(!view.includes('!discoverData.some'));
console.log('PASS: independent defaults, upgrade placement, saved IDs/order/visibility/custom rows preserved, idempotence and standalone rendering');
